  function extractGddpTokens(s) {
    var norm = normalizeStr(s);
    if (!norm) return [];
    var parts = norm.split(' ');
    var res = [];
    for (var i = 0; i < parts.length; i++) {
      var w = parts[i];
      if (w.length >= 2 && !GDDP_STOP_WORDS[w] && !/^\d+$/.test(w)) {
        res.push(w);
      }
    }
    return res;
  }

